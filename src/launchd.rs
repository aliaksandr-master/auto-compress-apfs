//! `install-launchd` / `uninstall-launchd`: a per-user launchd agent that starts a generated
//! shell script next to the config at load and daily at 09:00 local time. The script runs
//! `run --apply` (trash, purge, compress as configured) at most once per day and not before 09:00, so a run missed while the Mac
//! was off starts once at the next login; launchd itself coalesces runs missed during sleep.

use crate::shell_quote;
use crate::sys;
use std::fs;
use std::io;
use std::os::unix::fs::{MetadataExt, PermissionsExt};
use std::path::{Path, PathBuf};
use std::process::Command;
use std::thread;
use std::time::Duration;

pub const LABEL: &str = "local.auto-compress-apfs";
const LAUNCHCTL: &str = "/bin/launchctl";
/// The generated script, next to the config.
pub const SCRIPT_NAME: &str = "run.sh";
/// In the state dir: the local day (`YYYY-MM-DD`) of the last run the script started.
pub const LAST_RUN_NAME: &str = "last-run-day";
/// Local hour of the daily run; the script starts nothing earlier in the day.
const RUN_HOUR: u32 = 9;

/// Everything the agent and its script refer to, all absolute.
pub struct Agent {
    pub bin: PathBuf,
    /// Passed to the binary as `--config` (only when not the default).
    pub config: Option<PathBuf>,
    pub script: PathBuf,
    pub plist: PathBuf,
    pub launchd_log: PathBuf,
    pub last_run: PathBuf,
}

/// The script launchd starts. A missing binary is one line in `launchd.log` and exit 0. The run
/// itself `exec`s the binary: the job's process becomes the binary, so privacy (TCC) grants
/// for the binary apply rather than for `/bin/sh` (a hypothesis, see README); the binary
/// reports its own errors on stderr, which launchd appends to `launchd.log`.
/// `run_hour` is [`RUN_HOUR`] except in tests.
fn render_script(a: &Agent, run_hour: u32) -> String {
    let q = |p: &Path| shell_quote(&p.to_string_lossy());
    let config = a
        .config
        .as_deref()
        .map(|c| format!(" --config {}", q(c)))
        .unwrap_or_default();
    format!(
        r#"#!/bin/sh
# Generated by `auto-compress-apfs install-launchd`; started by the launchd agent {LABEL}
# at load and daily at {run_hour:02}:00. Runs `run --apply` at most once per day and not
# before {run_hour:02}:00. A missing binary is only logged.
BIN={bin}
LOG={log}
LAST={last}
log() {{ printf '%s run.sh: %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >> "$LOG"; }}
today=$(date +%Y-%m-%d)
[ "$(date +%H)" -lt {run_hour} ] && exit 0
[ "$(cat "$LAST" 2>/dev/null)" = "$today" ] && exit 0
if [ ! -x "$BIN" ]; then
    log "$BIN not found or not executable, run skipped"
    exit 0
fi
mkdir -p "$(dirname "$LAST")" && printf '%s\n' "$today" > "$LAST"
exec "$BIN" run --apply{config}
"#,
        bin = q(&a.bin),
        log = q(&a.launchd_log),
        last = q(&a.last_run),
    )
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

fn render_plist(a: &Agent) -> String {
    let x = |p: &Path| xml_escape(&p.to_string_lossy());
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by `auto-compress-apfs install-launchd`; removed by `uninstall-launchd`. -->
<plist version="1.0">
<dict>
	<key>Label</key>
	<string>{LABEL}</string>
	<key>ProgramArguments</key>
	<array>
		<string>/bin/sh</string>
		<string>{script}</string>
	</array>
	<key>StartCalendarInterval</key>
	<dict>
		<key>Hour</key>
		<integer>{RUN_HOUR}</integer>
		<key>Minute</key>
		<integer>0</integer>
	</dict>
	<key>RunAtLoad</key>
	<true/>
	<key>StandardOutPath</key>
	<string>{log}</string>
	<key>StandardErrorPath</key>
	<string>{log}</string>
	<key>Nice</key>
	<integer>10</integer>
</dict>
</plist>
"#,
        script = x(&a.script),
        log = x(&a.launchd_log),
    )
}

/// Directory of the plist: `~/Library/LaunchAgents`, or `ACZ_LAUNCH_AGENTS_DIR` (tests: writing
/// into a `Library/LaunchAgents` path, even below a temporary HOME, trips endpoint security
/// persistence detection).
pub fn agents_dir(home: &Path) -> PathBuf {
    std::env::var_os("ACZ_LAUNCH_AGENTS_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| home.join("Library/LaunchAgents"))
}

/// Whether launchctl is left out: set `ACZ_SKIP_LAUNCHCTL` (tests must never load an agent into
/// the real login session, in any build).
pub fn skip_launchctl() -> bool {
    std::env::var_os("ACZ_SKIP_LAUNCHCTL").is_some()
}

/// Runs `launchctl <args>`; `Err` carries its exit status and stderr.
fn launchctl(args: &[&str]) -> Result<(), String> {
    let out = Command::new(LAUNCHCTL)
        .args(args)
        .output()
        .map_err(|e| format!("cannot run {LAUNCHCTL}: {e}"))?;
    if out.status.success() {
        return Ok(());
    }
    let stderr = String::from_utf8_lossy(&out.stderr)
        .trim()
        .replace('\n', " | ");
    Err(format!(
        "{LAUNCHCTL} {}: {} {stderr}",
        args.join(" "),
        out.status
    ))
}

fn domain() -> String {
    format!("gui/{}", sys::effective_uid())
}

/// Replaces `path` by rename: a running `sh` keeps reading the old script.
fn write_file(path: &Path, text: &str, mode: u32) -> Result<(), String> {
    let err = |e: io::Error| format!("cannot write {}: {e}", path.display());
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).map_err(err)?;
    }
    let mut tmp = path.as_os_str().to_owned();
    tmp.push(format!(".tmp.{}", std::process::id()));
    let tmp = PathBuf::from(tmp);
    fs::write(&tmp, text)
        .and_then(|()| fs::set_permissions(&tmp, fs::Permissions::from_mode(mode)))
        .and_then(|()| fs::rename(&tmp, path))
        .map_err(|e| {
            let _ = fs::remove_file(&tmp);
            err(e)
        })
}

fn remove(path: &Path) -> Result<bool, String> {
    match fs::remove_file(path) {
        Ok(()) => Ok(true),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(e) => Err(format!("cannot remove {}: {e}", path.display())),
    }
}

/// Writes the script and the plist, then (re)loads the agent: a loaded agent with this label is
/// booted out first, so a reinstall replaces it.
pub fn install(a: &Agent) -> Result<(), String> {
    if sys::effective_uid() == 0 {
        return Err("install-launchd installs a per-user agent: run it as your user".into());
    }
    write_file(&a.script, &render_script(a, RUN_HOUR), 0o755)?;
    println!("wrote {}", a.script.display());
    if let Some(dir) = a.launchd_log.parent() {
        fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    }
    write_file(&a.plist, &render_plist(a), 0o644)?;
    println!("wrote {}", a.plist.display());
    if skip_launchctl() {
        println!("launchctl skipped (ACZ_SKIP_LAUNCHCTL is set), agent not loaded");
        return Ok(());
    }
    let domain = domain();
    let _ = launchctl(&["bootout", &format!("{domain}/{LABEL}")]);
    let plist = a.plist.to_string_lossy();
    let bootstrap = ["bootstrap", domain.as_str(), &plist];
    // bootout finishes asynchronously: an immediate bootstrap may fail once with EIO.
    if launchctl(&bootstrap).is_err() {
        thread::sleep(Duration::from_millis(500));
        launchctl(&bootstrap)?;
    }
    println!(
        "loaded {LABEL}: runs `{} run --apply` daily at {RUN_HOUR:02}:00 (a missed run starts \
         once after login or wake, from {RUN_HOUR:02}:00 on), log {}",
        a.bin.display(),
        a.launchd_log.display()
    );
    Ok(())
}

/// What `check-launchd` concludes.
#[derive(Debug, PartialEq, Eq)]
pub enum Verdict {
    UpToDate,
    /// Nothing is installed or loaded.
    Install(String),
    /// Something is installed but missing, stale, unloaded or points to a missing binary.
    Reinstall(String),
}

/// Undoes [`shell_quote`].
fn shell_unquote(s: &str) -> String {
    match s.strip_prefix('\'').and_then(|s| s.strip_suffix('\'')) {
        Some(inner) => inner.replace(r"'\''", "'"),
        None => s.to_owned(),
    }
}

/// The binary and `--config` an installed script runs; `None` without a `BIN=` line.
fn installed_params(script: &str) -> Option<(PathBuf, Option<PathBuf>)> {
    let bin = script.lines().find_map(|l| l.strip_prefix("BIN="))?;
    let config = script
        .lines()
        // `run --apply` now, `compress --apply` in older scripts (some without `exec`).
        .find_map(|l| l.split_once(" --apply --config ").map(|(_, c)| c));
    Some((
        PathBuf::from(shell_unquote(bin)),
        config.map(|c| PathBuf::from(shell_unquote(c))),
    ))
}

/// The script an installed plist starts (the argument after `/bin/sh`).
pub fn plist_script(plist: &str) -> Option<PathBuf> {
    let rest = plist.split_once("<string>/bin/sh</string>")?.1;
    let arg = rest.split_once("<string>")?.1.split_once("</string>")?.0;
    let arg = arg
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&amp;", "&");
    Some(PathBuf::from(arg))
}

/// The `--config` an installed script passes (`Some(None)`: the default config); `None` when
/// the script cannot be read or parsed.
pub fn installed_config(script: &Path) -> Option<Option<PathBuf>> {
    let text = fs::read_to_string(script).ok()?;
    installed_params(&text).map(|(_, c)| c)
}

/// Whether launchd has the agent loaded from `plist`.
fn loaded_from(plist: &Path) -> bool {
    Command::new(LAUNCHCTL)
        .args(["print", &format!("{}/{LABEL}", domain())])
        .output()
        .is_ok_and(|o| {
            o.status.success()
                && String::from_utf8_lossy(&o.stdout).contains(&*plist.to_string_lossy())
        })
}

/// Read-only check of an installation. The installed script names the binary and config it
/// runs; `agent_for` turns them into the [`Agent`] this version would install, whose script and
/// plist must equal the installed files byte for byte. `ask_launchd` is false in tests.
pub fn check(
    plist: &Path,
    script: &Path,
    ask_launchd: bool,
    agent_for: impl FnOnce(PathBuf, Option<PathBuf>) -> Result<Result<Agent, String>, String>,
) -> Result<Verdict, String> {
    let read = |p: &Path| match fs::read_to_string(p) {
        Ok(t) => Ok(Some(t)),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(format!("cannot read {}: {e}", p.display())),
    };
    let (installed_script, installed_plist) = (read(script)?, read(plist)?);
    let loaded = ask_launchd && loaded_from(plist);
    let reinstall = |why: String| Ok(Verdict::Reinstall(why));
    let (installed_script, installed_plist) = match (installed_script, installed_plist) {
        (None, None) if !loaded => {
            return Ok(Verdict::Install(
                "the launchd agent is not installed".into(),
            ));
        }
        (None, _) => return reinstall(format!("{} is missing", script.display())),
        (_, None) => return reinstall(format!("{} is missing", plist.display())),
        (Some(s), Some(p)) => (s, p),
    };
    let Some((bin, config)) = installed_params(&installed_script) else {
        return reinstall(format!(
            "{} was written by another version",
            script.display()
        ));
    };
    // Inner `Err`: a reason to reinstall (the config run.sh names is gone).
    let a = match agent_for(bin, config)? {
        Ok(a) => a,
        Err(why) => return reinstall(why),
    };
    if installed_script != render_script(&a, RUN_HOUR) {
        return reinstall(format!(
            "{} differs from what install-launchd writes now (another version or a changed \
             log_dir)",
            script.display()
        ));
    }
    if installed_plist != render_plist(&a) {
        return reinstall(format!(
            "{} differs from what install-launchd writes now (another version or a changed \
             log_dir)",
            plist.display()
        ));
    }
    let executable = fs::metadata(&a.bin).is_ok_and(|m| m.is_file() && m.mode() & 0o111 != 0);
    if !executable {
        return reinstall(format!(
            "the binary it runs, {}, is missing or not executable",
            a.bin.display()
        ));
    }
    if ask_launchd && !loaded {
        return reinstall("the agent is not loaded in launchd".into());
    }
    Ok(Verdict::UpToDate)
}

/// Unloads the agent and removes `plist` and `script`; anything already gone is fine.
pub fn uninstall(plist: &Path, script: &Path) -> Result<(), String> {
    if !skip_launchctl() {
        match launchctl(&["bootout", &format!("{}/{LABEL}", domain())]) {
            Ok(()) => println!("unloaded {LABEL}"),
            Err(_) => println!("{LABEL} was not loaded"),
        }
    }
    for p in [plist, script] {
        if remove(p)? {
            println!("removed {}", p.display());
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn agent(dir: &Path, config: Option<&str>) -> Agent {
        Agent {
            bin: dir.join("bin dir/fake-bin"),
            config: config.map(PathBuf::from),
            script: dir.join(SCRIPT_NAME),
            plist: dir.join("agent.plist"),
            launchd_log: dir.join("logs/launchd.log"),
            last_run: dir.join("state/last-run-day"),
        }
    }

    fn temp_dir(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("acz-launchd-{tag}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    /// Runs the script rendered with `run_hour`; returns its exit success.
    fn run(a: &Agent, run_hour: u32) -> bool {
        write_file(&a.script, &render_script(a, run_hour), 0o755).unwrap();
        Command::new("/bin/sh")
            .arg(&a.script)
            .status()
            .unwrap()
            .success()
    }

    fn read(p: &Path) -> String {
        fs::read_to_string(p).unwrap_or_default()
    }

    #[test]
    fn script_runs_once_per_day() {
        let dir = temp_dir("script");
        let a = agent(&dir, Some("/c d/x.toml"));
        fs::create_dir_all(a.launchd_log.parent().unwrap()).unwrap();
        // Missing binary: one log line, exit 0, no day recorded.
        assert!(run(&a, 0));
        assert!(read(&a.launchd_log).contains("fake-bin not found or not executable"));
        assert!(!a.last_run.exists());
        // The binary records its arguments; its exit status is the job's.
        let calls = dir.join("calls");
        let fake = format!("#!/bin/sh\necho \"$*\" >> '{}'\n", calls.display());
        write_file(&a.bin, &fake, 0o755).unwrap();
        assert!(run(&a, 0));
        assert_eq!(read(&calls), "run --apply --config /c d/x.toml\n");
        assert_eq!(read(&a.last_run).trim().len(), "YYYY-MM-DD".len());
        // Already run today: nothing started.
        assert!(run(&a, 0));
        assert_eq!(read(&calls).lines().count(), 1);
        // Another day recorded: runs again.
        fs::write(&a.last_run, "2000-01-01\n").unwrap();
        assert!(run(&a, 0));
        assert_eq!(read(&calls).lines().count(), 2);
        // Before the run hour: nothing started (hour 24 is never reached).
        fs::write(&a.last_run, "2000-01-01\n").unwrap();
        assert!(run(&a, 24));
        assert_eq!(read(&calls).lines().count(), 2);
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn installed_params_undo_the_quoting() {
        let dir = temp_dir("params");
        let mut a = agent(&dir, Some("/c 'q' $x/a.toml"));
        a.bin = PathBuf::from("/b i'n/x");
        let s = render_script(&a, RUN_HOUR);
        assert_eq!(
            installed_params(&s),
            Some((a.bin.clone(), a.config.clone()))
        );
        a.config = None;
        let s = render_script(&a, RUN_HOUR);
        assert_eq!(installed_params(&s), Some((a.bin.clone(), None)));
        assert_eq!(installed_params("#!/bin/sh\n"), None);
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn check_tells_install_reinstall_and_up_to_date() {
        let dir = temp_dir("check");
        let a = agent(&dir, None);
        let check = || {
            check(&a.plist, &a.script, false, |bin, config| {
                Ok(Ok(Agent {
                    bin,
                    config,
                    ..agent(&dir, None)
                }))
            })
            .unwrap()
        };
        assert!(matches!(check(), Verdict::Install(_)));
        // The plist names its script; a missing config is a reason to reinstall.
        assert_eq!(plist_script(&render_plist(&a)), Some(a.script.clone()));
        let gone = super::check(&a.plist, &a.script, false, |_, _| {
            Ok(Err("config gone".into()))
        });
        write_file(&a.script, &render_script(&a, RUN_HOUR), 0o755).unwrap();
        assert!(matches!(check(), Verdict::Reinstall(w) if w.contains("agent.plist is missing")));
        write_file(&a.plist, &render_plist(&a), 0o644).unwrap();
        assert!(
            matches!(check(), Verdict::Reinstall(w) if w.contains("is missing or not executable"))
        );
        write_file(&a.bin, "#!/bin/sh\n", 0o755).unwrap();
        assert_eq!(check(), Verdict::UpToDate);
        assert!(matches!(gone, Ok(Verdict::Install(_))));
        let gone = super::check(&a.plist, &a.script, false, |_, _| {
            Ok(Err("config gone".into()))
        });
        assert_eq!(gone, Ok(Verdict::Reinstall("config gone".into())));
        // A script of another version (here: an older one without exec).
        let old = render_script(&a, RUN_HOUR).replace("exec \"$BIN\"", "\"$BIN\"");
        write_file(&a.script, &old, 0o755).unwrap();
        assert!(matches!(check(), Verdict::Reinstall(w) if w.contains("differs from")));
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn default_config_is_not_passed() {
        let dir = temp_dir("noconfig");
        let s = render_script(&agent(&dir, None), RUN_HOUR);
        assert!(s.contains("exec \"$BIN\" run --apply\n"), "{s}");
        assert!(s.contains("BIN='"), "path with a space is quoted: {s}");
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn plist_is_valid_and_escaped() {
        let dir = temp_dir("plist & <x>");
        let a = agent(&dir, None);
        write_file(&a.plist, &render_plist(&a), 0o644).unwrap();
        let lint = Command::new("/usr/bin/plutil")
            .arg("-lint")
            .arg(&a.plist)
            .output()
            .unwrap();
        assert!(lint.status.success(), "{lint:?}");
        let text = read(&a.plist);
        assert!(text.contains("plist &amp; &lt;x&gt;"), "{text}");
        assert!(text.contains("<key>RunAtLoad</key>\n\t<true/>"));
        fs::remove_dir_all(&dir).unwrap();
    }
}

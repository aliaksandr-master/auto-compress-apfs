//! `install-launchd` / `uninstall-launchd`: a per-user launchd agent that starts a generated
//! shell script next to the config at load and daily at 09:00 local time. The script runs
//! `compress --apply` at most once per day and not before 09:00, so a run missed while the Mac
//! was off starts once at the next login; launchd itself coalesces runs missed during sleep.

use crate::shell_quote;
use crate::sys;
use std::fs;
use std::io;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::thread;
use std::time::Duration;

pub const LABEL: &str = "local.auto-compress-apfs";
const LAUNCHCTL: &str = "/bin/launchctl";
/// The generated script, next to the config.
pub const SCRIPT_NAME: &str = "run.sh";
/// In the state dir: the local day (`YYYY-MM-DD`) of the last run the script started.
pub const LAST_RUN_NAME: &str = "last-run-day";
/// Local hour of the daily run; the script starts nothing earlier in the day.
const RUN_HOUR: u32 = 9;

/// Everything the agent and its script refer to, all absolute.
pub struct Agent {
    pub bin: PathBuf,
    /// Passed to the binary as `--config` (only when not the default).
    pub config: Option<PathBuf>,
    pub script: PathBuf,
    pub plist: PathBuf,
    pub launchd_log: PathBuf,
    pub last_run: PathBuf,
}

/// The script launchd starts. A missing binary is one line in `launchd.log` and exit 0. The run
/// itself `exec`s the binary: the job's process becomes the binary, so privacy (TCC) grants
/// for the binary apply rather than for `/bin/sh` (a hypothesis, see README); the binary
/// reports its own errors on stderr, which launchd appends to `launchd.log`.
/// `run_hour` is [`RUN_HOUR`] except in tests.
fn render_script(a: &Agent, run_hour: u32) -> String {
    let q = |p: &Path| shell_quote(&p.to_string_lossy());
    let config = a
        .config
        .as_deref()
        .map(|c| format!(" --config {}", q(c)))
        .unwrap_or_default();
    format!(
        r#"#!/bin/sh
# Generated by `auto-compress-apfs install-launchd`; started by the launchd agent {LABEL}
# at load and daily at {run_hour:02}:00. Runs `compress --apply` at most once per day and not
# before {run_hour:02}:00. A missing binary is only logged.
BIN={bin}
LOG={log}
LAST={last}
log() {{ printf '%s run.sh: %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >> "$LOG"; }}
today=$(date +%Y-%m-%d)
[ "$(date +%H)" -lt {run_hour} ] && exit 0
[ "$(cat "$LAST" 2>/dev/null)" = "$today" ] && exit 0
if [ ! -x "$BIN" ]; then
    log "$BIN not found or not executable, run skipped"
    exit 0
fi
mkdir -p "$(dirname "$LAST")" && printf '%s\n' "$today" > "$LAST"
exec "$BIN" compress --apply{config}
"#,
        bin = q(&a.bin),
        log = q(&a.launchd_log),
        last = q(&a.last_run),
    )
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

fn render_plist(a: &Agent) -> String {
    let x = |p: &Path| xml_escape(&p.to_string_lossy());
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by `auto-compress-apfs install-launchd`; removed by `uninstall-launchd`. -->
<plist version="1.0">
<dict>
	<key>Label</key>
	<string>{LABEL}</string>
	<key>ProgramArguments</key>
	<array>
		<string>/bin/sh</string>
		<string>{script}</string>
	</array>
	<key>StartCalendarInterval</key>
	<dict>
		<key>Hour</key>
		<integer>{RUN_HOUR}</integer>
		<key>Minute</key>
		<integer>0</integer>
	</dict>
	<key>RunAtLoad</key>
	<true/>
	<key>StandardOutPath</key>
	<string>{log}</string>
	<key>StandardErrorPath</key>
	<string>{log}</string>
	<key>Nice</key>
	<integer>10</integer>
</dict>
</plist>
"#,
        script = x(&a.script),
        log = x(&a.launchd_log),
    )
}

/// Whether launchctl is left out: set `ACZ_SKIP_LAUNCHCTL` (tests must never load an agent into
/// the real login session, in any build).
fn skip_launchctl() -> bool {
    std::env::var_os("ACZ_SKIP_LAUNCHCTL").is_some()
}

/// Runs `launchctl <args>`; `Err` carries its exit status and stderr.
fn launchctl(args: &[&str]) -> Result<(), String> {
    let out = Command::new(LAUNCHCTL)
        .args(args)
        .output()
        .map_err(|e| format!("cannot run {LAUNCHCTL}: {e}"))?;
    if out.status.success() {
        return Ok(());
    }
    let stderr = String::from_utf8_lossy(&out.stderr)
        .trim()
        .replace('\n', " | ");
    Err(format!(
        "{LAUNCHCTL} {}: {} {stderr}",
        args.join(" "),
        out.status
    ))
}

fn domain() -> String {
    format!("gui/{}", sys::effective_uid())
}

/// Replaces `path` by rename: a running `sh` keeps reading the old script.
fn write_file(path: &Path, text: &str, mode: u32) -> Result<(), String> {
    let err = |e: io::Error| format!("cannot write {}: {e}", path.display());
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).map_err(err)?;
    }
    let mut tmp = path.as_os_str().to_owned();
    tmp.push(format!(".tmp.{}", std::process::id()));
    let tmp = PathBuf::from(tmp);
    fs::write(&tmp, text)
        .and_then(|()| fs::set_permissions(&tmp, fs::Permissions::from_mode(mode)))
        .and_then(|()| fs::rename(&tmp, path))
        .map_err(|e| {
            let _ = fs::remove_file(&tmp);
            err(e)
        })
}

fn remove(path: &Path) -> Result<bool, String> {
    match fs::remove_file(path) {
        Ok(()) => Ok(true),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(e) => Err(format!("cannot remove {}: {e}", path.display())),
    }
}

/// Writes the script and the plist, then (re)loads the agent: a loaded agent with this label is
/// booted out first, so a reinstall replaces it.
pub fn install(a: &Agent) -> Result<(), String> {
    if sys::effective_uid() == 0 {
        return Err("install-launchd installs a per-user agent: run it as your user".into());
    }
    write_file(&a.script, &render_script(a, RUN_HOUR), 0o755)?;
    println!("wrote {}", a.script.display());
    if let Some(dir) = a.launchd_log.parent() {
        fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    }
    write_file(&a.plist, &render_plist(a), 0o644)?;
    println!("wrote {}", a.plist.display());
    if skip_launchctl() {
        println!("launchctl skipped (ACZ_SKIP_LAUNCHCTL is set), agent not loaded");
        return Ok(());
    }
    let domain = domain();
    let _ = launchctl(&["bootout", &format!("{domain}/{LABEL}")]);
    let plist = a.plist.to_string_lossy();
    let bootstrap = ["bootstrap", domain.as_str(), &plist];
    // bootout finishes asynchronously: an immediate bootstrap may fail once with EIO.
    if launchctl(&bootstrap).is_err() {
        thread::sleep(Duration::from_millis(500));
        launchctl(&bootstrap)?;
    }
    println!(
        "loaded {LABEL}: runs `{} compress --apply` daily at {RUN_HOUR:02}:00 (a missed run starts \
         once after login or wake, from {RUN_HOUR:02}:00 on), log {}",
        a.bin.display(),
        a.launchd_log.display()
    );
    Ok(())
}

/// Unloads the agent and removes `plist` and `script`; anything already gone is fine.
pub fn uninstall(plist: &Path, script: &Path) -> Result<(), String> {
    if !skip_launchctl() {
        match launchctl(&["bootout", &format!("{}/{LABEL}", domain())]) {
            Ok(()) => println!("unloaded {LABEL}"),
            Err(_) => println!("{LABEL} was not loaded"),
        }
    }
    for p in [plist, script] {
        if remove(p)? {
            println!("removed {}", p.display());
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn agent(dir: &Path, config: Option<&str>) -> Agent {
        Agent {
            bin: dir.join("bin dir/fake-bin"),
            config: config.map(PathBuf::from),
            script: dir.join(SCRIPT_NAME),
            plist: dir.join("agent.plist"),
            launchd_log: dir.join("logs/launchd.log"),
            last_run: dir.join("state/last-run-day"),
        }
    }

    fn temp_dir(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("acz-launchd-{tag}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    /// Runs the script rendered with `run_hour`; returns its exit success.
    fn run(a: &Agent, run_hour: u32) -> bool {
        write_file(&a.script, &render_script(a, run_hour), 0o755).unwrap();
        Command::new("/bin/sh")
            .arg(&a.script)
            .status()
            .unwrap()
            .success()
    }

    fn read(p: &Path) -> String {
        fs::read_to_string(p).unwrap_or_default()
    }

    #[test]
    fn script_runs_once_per_day() {
        let dir = temp_dir("script");
        let a = agent(&dir, Some("/c d/x.toml"));
        fs::create_dir_all(a.launchd_log.parent().unwrap()).unwrap();
        // Missing binary: one log line, exit 0, no day recorded.
        assert!(run(&a, 0));
        assert!(read(&a.launchd_log).contains("fake-bin not found or not executable"));
        assert!(!a.last_run.exists());
        // The binary records its arguments; its exit status is the job's.
        let calls = dir.join("calls");
        let fake = format!("#!/bin/sh\necho \"$*\" >> '{}'\n", calls.display());
        write_file(&a.bin, &fake, 0o755).unwrap();
        assert!(run(&a, 0));
        assert_eq!(read(&calls), "compress --apply --config /c d/x.toml\n");
        assert_eq!(read(&a.last_run).trim().len(), "YYYY-MM-DD".len());
        // Already run today: nothing started.
        assert!(run(&a, 0));
        assert_eq!(read(&calls).lines().count(), 1);
        // Another day recorded: runs again.
        fs::write(&a.last_run, "2000-01-01\n").unwrap();
        assert!(run(&a, 0));
        assert_eq!(read(&calls).lines().count(), 2);
        // Before the run hour: nothing started (hour 24 is never reached).
        fs::write(&a.last_run, "2000-01-01\n").unwrap();
        assert!(run(&a, 24));
        assert_eq!(read(&calls).lines().count(), 2);
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn default_config_is_not_passed() {
        let dir = temp_dir("noconfig");
        let s = render_script(&agent(&dir, None), RUN_HOUR);
        assert!(s.contains("exec \"$BIN\" compress --apply\n"), "{s}");
        assert!(s.contains("BIN='"), "path with a space is quoted: {s}");
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn plist_is_valid_and_escaped() {
        let dir = temp_dir("plist & <x>");
        let a = agent(&dir, None);
        write_file(&a.plist, &render_plist(&a), 0o644).unwrap();
        let lint = Command::new("/usr/bin/plutil")
            .arg("-lint")
            .arg(&a.plist)
            .output()
            .unwrap();
        assert!(lint.status.success(), "{lint:?}");
        let text = read(&a.plist);
        assert!(text.contains("plist &amp; &lt;x&gt;"), "{text}");
        assert!(text.contains("<key>RunAtLoad</key>\n\t<true/>"));
        fs::remove_dir_all(&dir).unwrap();
    }
}
